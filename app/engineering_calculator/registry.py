def search_formulas(query=""):
    """Search formula names, categories, descriptions, equations, and keywords."""
    query = query.strip().casefold()
    matches = []

    for category, formulas in FORMULA_REGISTRY.items():
        for name, details in formulas.items():
            searchable_text = " ".join(
                [
                    category,
                    name,
                    details["description"],
                    details["equation"],
                    *details["keywords"],
                ]
            ).casefold()

            if not query or query in searchable_text:
                matches.append(
                    {
                        "category": category,
                        "name": name,
                        **details,
                    }
                )

    return matches


def get_formula(category, name):
    """Return a formula definition by category and name."""
    try:
        return FORMULA_REGISTRY[category][name]
    except KeyError as exc:
        raise ValueError(
            f"Unknown formula '{name}' in category '{category}'."
        ) from exc
